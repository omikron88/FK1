void AtKeyboard::reset() noexcept
{
    czech_ = acute_ = caron_ = hex_pending_ = false;
    hex_high_ = 0;
}

std::optional<std::uint8_t> AtKeyboard::translate(
    const std::uint8_t scan, const bool extended, const bool shift,
    const bool caps, const bool control, const bool num, const bool scroll) noexcept
{
    // Enable the Alt language toggle commented out in Z_ALT in the supplied firmware.
    if(scan == 0x11) {
        czech_ = !czech_;
        return std::nullopt;
    }
    if(!scroll) {
        hex_pending_ = false;
    }
    std::uint8_t code = 0;
    if(extended) {
        if(scan == 0x5A) code = 0x0D;
        else if(scan == 0x4A) code = '/';
        else {
            if(num || scan < 0x69 || scan > 0x7D) return std::nullopt;
            const auto index = static_cast<unsigned>(scan) + 27U + (shift ? 21U : 0U);
            code = us_mp[index];
        }
    } else {
        if(scan >= sizeof(us_vp)) return std::nullopt;
        if(czech_ && scan == 0x55) {
            if(shift) caron_ = true;
            else acute_ = true;
            return std::nullopt;
        }
        const auto* table = czech_ ? (shift != caps ? cz_vp : cz_mp)
                                  : (shift != caps ? us_vp : us_mp);
        code = table[scan];
        if(code == 0) return std::nullopt;
        if(scroll) {
            int digit = -1;
            if(code >= '0' && code <= '9') digit = code - '0';
            if(code >= 'a' && code <= 'f') digit = code - 'a' + 10;
            if(code >= 'A' && code <= 'F') digit = code - 'A' + 10;
            if(digit < 0) return std::nullopt;
            if(!hex_pending_) {
                hex_high_ = static_cast<std::uint8_t>(digit);
                hex_pending_ = true;
                return std::nullopt;
            }
            code = static_cast<std::uint8_t>(hex_high_ * 16U + static_cast<unsigned>(digit));
            hex_pending_ = false;
        } else if(czech_ && (acute_ || caron_)) {
            const auto character = static_cast<std::uint8_t>(code & 0x7FU);
            if(character > '@' && character < '{') {
                const auto index = static_cast<unsigned>(character & 0xDFU) - 'A';
                const auto accent = index < 26U ? (acute_ ? cz_car : cz_hac)[index] : std::uint8_t{0};
                if(accent != 0) code = static_cast<std::uint8_t>(accent + (shift ? 0x20U : 0U));
            }
            if(acute_) acute_ = false;
            else caron_ = false;
        } else if(control) {
            const auto character = static_cast<std::uint8_t>(code & 0x7FU);
            if(character < '?') return std::nullopt;
            if(character != '?') code = static_cast<std::uint8_t>(character & 0x1FU);
        }
    }
    // OUTPUT swaps KOI-8 letter case, including extended/function/hex bytes.
    if(czech_ && code >= 0xC0) code ^= 0x20;
    // Table zero suppresses a key, but Ctrl+@ and hexadecimal 00 are real output.
    if(extended && code == 0) return std::nullopt;
    return code;
}

